namespace Wpf.Ui.Violeta.Controls;

/// <summary>
/// Alignment of the active carousel page within the viewport.
/// Mirrors Fluent UI React <c>align</c>.
/// </summary>
public enum CarouselAlign
{
    /// <summary>Align the active page to the start (left).</summary>
    Start,

    /// <summary>Center the active page.</summary>
    Center,

    /// <summary>Align the active page to the end (right).</summary>
    End,
}
