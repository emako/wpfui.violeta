/// <summary>
/// Defines a specific component in the HSV color model.
/// </summary>
public enum HsvComponent
{
    /// <summary>The Alpha component.</summary>
    Alpha = 0,

    /// <summary>The Hue component.</summary>
    Hue = 1,

    /// <summary>The Saturation component.</summary>
    Saturation = 2,

    /// <summary>The Value component.</summary>
    Value = 3,
}
